#include <string>
// 챗 봇의 코드 개선
#include <vector>
#include <sstream>
#include <algorithm>

using namespace std;

string solution(string s) {
    int minNum, maxNum;
    int temp; // 현재 읽어들인 숫자를 담을 변수
    
    stringstream ss(s);
    
    // 1. 첫 번째 숫자를 먼저 읽어서 초기값으로 설정합니다.
    ss >> temp;
    minNum = temp;
    maxNum = temp;
    
    // 2. 두 번째 숫자부터 끝까지 읽으며 비교합니다.
    while(ss >> temp) {
        if (temp < minNum) minNum = temp;
        if (temp > maxNum) maxNum = temp;
    }
    
    // 3. 결과를 포맷에 맞춰 반환합니다.
    return to_string(minNum) + " " + to_string(maxNum);
}

