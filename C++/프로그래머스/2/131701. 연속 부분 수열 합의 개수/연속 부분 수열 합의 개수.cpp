#include <string>
#include <vector>
#include <unordered_set>

using namespace std;

int solution(vector<int> elements) {
    unordered_set<int> addResults;
    int n = elements.size();
    
    // 1. 원형 수열 처리를 쉽게 하기 위해 배열을 2배로 늘립니다.
    vector<int> extended_elements(elements);
    extended_elements.insert(extended_elements.end(), elements.begin(), elements.end());
    
    // 2. 시작 인덱스 i를 기준으로 반복합니다. (0부터 n-1까지)
    for (int i = 0; i < n; ++i) {
        int current_sum = 0;
        
        // 3. 길이를 1부터 n까지 늘려가며 이전 합에 다음 원소를 더합니다.
        for (int j = i; j < i + n; ++j) {
            current_sum += extended_elements[j];
            addResults.insert(current_sum);
        }
    }
    
    // 4. 중복이 제거된 부분 수열 합의 개수를 반환합니다.
    return addResults.size();
}

