#include <string>
#include <vector>
#include <algorithm> // count 함수 사용을 위해 필요

using namespace std;

vector<int> solution(string s) {
    int convertCount = 0;
    int zeroCount = 0;

    while (s != "1") {
        convertCount++;
        
        // 1. 현재 문자열에서 '1'의 개수 세기 (std::count 활용)
        // 전체 길이 - 1의 개수 = 0의 개수
        int oneCnt = count(s.begin(), s.end(), '1');
        zeroCount += (s.length() - oneCnt);

        // 2. '1'의 개수(oneCnt)를 다시 이진수 문자열로 변환
        // 이진 변환 결과를 s에 저장
        s = "";
        int temp = oneCnt;
        
        while (temp > 0) {
            // 나머지가 1이면 '1', 아니면 '0' 추가
            s += (temp % 2 + '0'); 
            temp /= 2;
        }
        
        // 만약 oneCnt가 1이었다면 s는 "1"이 되고 루프 종료
    }

    return {convertCount, zeroCount};
}

