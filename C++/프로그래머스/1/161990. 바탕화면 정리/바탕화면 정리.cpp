// 챗봇의 개선사항
#include <string>
#include <vector>
#include <algorithm>
#include <climits> // INT_MAX, INT_MIN 사용을 위해 포함

using namespace std;

vector<int> solution(vector<string> wallpaper) {
    // 1. 초기값을 정수 범위의 최대/최소로 설정하여 안전성 확보
    int lux = INT_MAX;
    int luy = INT_MAX;
    int rdx = INT_MIN;
    int rdy = INT_MIN;

    // 2. 바탕화면 전체를 순회하며 파일('#') 위치 탐색
    for(int i = 0; i < wallpaper.size(); ++i) {
        for(int j = 0; j < wallpaper[i].size(); ++j) {
            if(wallpaper[i][j] == '#') {
                // 가장 왼쪽, 위쪽 좌표 갱신
                lux = min(lux, i);
                luy = min(luy, j);
                // 가장 오른쪽, 아래쪽 좌표 갱신
                rdx = max(rdx, i);
                rdy = max(rdy, j);
            }
        }
    }

    // 3. rdx, rdy는 해당 칸의 우하단 좌표여야 하므로 +1 하여 반환
    // vector를 명시적으로 push_back 하지 않고 초기화 리스트 사용
    return {lux, luy, rdx + 1, rdy + 1};
}

