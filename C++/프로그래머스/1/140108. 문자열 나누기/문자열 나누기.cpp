// 챗 봇의 개선 코드
#include <string>
#include <vector>

using namespace std;

int solution(string s) {
    int answer = 0;
    
    // 현재 비교 기준이 되는 문자 (초기화 상태는 0 또는 null)
    char x = 0; 
    
    // x의 개수와 x가 아닌 글자의 개수
    int x_count = 0;
    int other_count = 0;

    // 범위 기반 for 문을 사용하여 문자열의 각 문자를 순회
    for (const char c : s) {
        // 1. 새로운 분리 문자열의 시작인 경우 (초기화 상태)
        if (x == 0) {
            x = c;
            x_count++;
            continue; // 첫 글자 세팅 후 다음 로직 건너뜀
        }

        // 2. 현재 문자가 기준 문자와 같은지 다른지 카운트
        if (x == c) {
            x_count++;
        } else {
            other_count++;
        }

        // 3. 두 횟수가 같아지면 문자열 분리
        if (x_count == other_count) {
            answer++;
            // 상태 초기화: 다음 문자가 새로운 기준 문자가 되도록 함
            x = 0;
            x_count = 0;
            other_count = 0;
        }
    }

    // 4. 반복문 종료 후, 분리되지 않고 남은 문자열이 있다면 카운트 추가
    // x가 0이 아니라는 것은 처리 중인 문자가 남아있다는 뜻입니다.
    if (x != 0) {
        answer++;
    }

    return answer;
}

